// Writes database/sql/schema.sql: the whole schema as plain MySQL, built from the Drizzle models.
// A fresh database (the MySQL container's first start) is created from this file, because
// `drizzle-kit push` cannot create it reliably. Run `npm run db:schema` after changing a model and
// commit the result.
import { spawnSync } from "node:child_process";
import { mkdirSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const kit = resolve(root, "node_modules/drizzle-kit/bin.cjs");
const result = spawnSync(process.execPath, [kit, "export"], { cwd: root, encoding: "utf8" });

if (result.status !== 0) {
  console.error(result.stderr || result.stdout);
  process.exit(result.status ?? 1);
}

const sql = result.stdout
  .replaceAll("\r\n", "\n")
  // drizzle-kit prints this placeholder where MySQL wants nothing
  .replaceAll("ALGORITHM = undefined ", "")
  .trim();
const header = [
  "-- Pharma Vault schema (generated by `npm run db:schema`; do not edit by hand).",
  "-- Creates every table, index, constraint and view on an empty database.",
  "",
  "",
].join("\n");

mkdirSync(resolve(root, "database/sql"), { recursive: true });
writeFileSync(resolve(root, "database/sql/schema.sql"), `${header}${sql}\n`);
console.log(`Wrote database/sql/schema.sql (${sql.split("\n").length} lines)`);
